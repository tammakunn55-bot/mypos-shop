-- ---------- 1) ลูกค้า ----------
create table if not exists customers (
  id           bigint generated by default as identity primary key,
  name         text not null,
  phone        text,
  address      text,
  tax_id       text,
  note         text,
  credit_limit numeric(12,2) not null default 0 check (credit_limit >= 0),  -- 0 = ไม่จำกัด
  is_active    boolean not null default true,
  created_at   timestamptz not null default now(),
  updated_at   timestamptz not null default now()
);
create index if not exists customers_name_idx on customers (name);

create table if not exists customer_payments (   -- รับชำระหนี้
  id          bigint generated by default as identity primary key,
  customer_id bigint not null references customers(id),
  amount      numeric(12,2) not null check (amount > 0),
  method      text not null default 'cash' check (method in ('cash','transfer','promptpay','other')),
  note        text,
  staff_id    uuid default auth.uid(),
  created_at  timestamptz not null default now()
);
create index if not exists customer_payments_cust_idx on customer_payments (customer_id);

alter table sales add column if not exists customer_id bigint references customers(id);
create index if not exists sales_customer_idx on sales (customer_id) where customer_id is not null;
alter table sales drop constraint if exists sales_pay_method_check;
alter table sales add constraint sales_pay_method_check check (pay_method in ('cash','transfer','promptpay','other','credit'));

drop trigger if exists t_customers_upd on customers;
create trigger t_customers_upd before update on customers for each row execute function set_updated_at();

alter table customers         enable row level security;
alter table customer_payments enable row level security;
drop policy if exists "staff_read"   on customers;
drop policy if exists "staff_insert" on customers;
drop policy if exists "staff_update" on customers;
drop policy if exists "owner_delete" on customers;
create policy "staff_read"   on customers for select to authenticated using (is_staff());
create policy "staff_insert" on customers for insert to authenticated with check (is_staff());
create policy "staff_update" on customers for update to authenticated using (is_staff()) with check (is_staff());
create policy "owner_delete" on customers for delete to authenticated using (is_owner());
drop policy if exists "staff_read"   on customer_payments;
drop policy if exists "staff_insert" on customer_payments;
drop policy if exists "owner_delete" on customer_payments;
create policy "staff_read"   on customer_payments for select to authenticated using (is_staff());
create policy "staff_insert" on customer_payments for insert to authenticated with check (is_staff());
create policy "owner_delete" on customer_payments for delete to authenticated using (is_owner());

-- ยอดค้างของลูกค้าทุกคน (พนักงานเรียกได้ แต่ไม่เห็นบิลอื่นของร้าน)
create or replace function customer_balances()
returns table (customer_id bigint, credit_total numeric, paid_total numeric, balance numeric)
language sql stable security definer set search_path = public as $$
  select x.id, x.cr, x.pd, x.cr - x.pd
  from (select c.id,
          coalesce((select sum(s.total) from sales s where s.customer_id = c.id and s.pay_method = 'credit' and s.status = 'paid'), 0) as cr,
          coalesce((select sum(p.amount) from customer_payments p where p.customer_id = c.id), 0) as pd
        from customers c) x
  where is_staff();
$$;

-- รายการบิลเชื่อ + การรับชำระของลูกค้าคนเดียว
create or replace function customer_ledger(p_customer bigint) returns jsonb
language plpgsql stable security definer set search_path = public as $$
begin
  if not is_staff() then raise exception 'ไม่มีสิทธิ์ใช้งาน'; end if;
  return jsonb_build_object(
    'sales', (select coalesce(jsonb_agg(x order by x.at desc), '[]'::jsonb) from (
        select s.id, s.bill_no, s.total, s.status, coalesce(s.paid_at, s.created_at) as at
        from sales s where s.customer_id = p_customer and s.pay_method = 'credit' and s.status in ('paid','void')) x),
    'payments', (select coalesce(jsonb_agg(y order by y.at desc), '[]'::jsonb) from (
        select p.id, p.amount, p.method, p.note, p.created_at as at
        from customer_payments p where p.customer_id = p_customer) y));
end $$;

revoke execute on function customer_balances() from public, anon;
revoke execute on function customer_ledger(bigint) from public, anon;
grant  execute on function customer_balances() to authenticated;
grant  execute on function customer_ledger(bigint) to authenticated;

-- ---------- 2) สร้างบิล (รองรับขายเชื่อ) ----------
drop function if exists create_sale(text, bigint, text, numeric, jsonb, uuid, timestamptz);
create or replace function create_sale(
  p_status    text,         -- 'paid' = จ่ายแล้วและตัดสต็อก, 'held' = พักบิล (ยังไม่ตัดสต็อก)
  p_device    bigint,
  p_method    text,         -- cash / transfer / promptpay / other (ใช้เมื่อ paid)
  p_discount  numeric,
  p_items     jsonb,        -- [{"unit_id":123,"qty":2.5}, ...]
  p_client_id uuid        default null,   -- รหัสบิลที่เครื่องสร้าง ส่งซ้ำแล้วไม่เกิดบิลซ้ำ
  p_paid_at   timestamptz default null,   -- เวลาที่ขายจริง (ไม่เกินเวลาปัจจุบัน)
  p_customer  bigint      default null    -- ลูกค้า (จำเป็นเมื่อขายเชื่อ p_method = 'credit')
) returns jsonb
language plpgsql security definer set search_path = public as $$
declare
  v_sale  sales;
  v_staff uuid;
  v_paid  timestamptz;
  v_sub   numeric(12,2) := 0;
  v_disc  numeric(12,2);
  it      jsonb;
  u       product_units;
  p       products;
  v_qty   numeric;
  v_price numeric;
  v_base  numeric;
  v_item  bigint;
begin
  if not exists (select 1 from staff st where st.id = auth.uid()) then raise exception 'ไม่มีสิทธิ์ใช้งาน'; end if;
  if p_status not in ('held','paid') then raise exception 'สถานะบิลไม่ถูกต้อง'; end if;
  if p_items is null or jsonb_array_length(p_items) = 0 then raise exception 'ตะกร้าว่าง'; end if;
  if p_status = 'paid' and p_method not in ('cash','transfer','promptpay','other','credit') then
    raise exception 'ต้องระบุวิธีชำระเงิน';
  end if;

  if p_method = 'credit' and p_status = 'paid' and not exists (select 1 from customers c where c.id = p_customer and c.is_active) then
    raise exception 'ขายเชื่อต้องเลือกลูกค้า';
  end if;

  if p_client_id is not null then            -- เคยบันทึกแล้ว: คืนบิลเดิม ไม่สร้างซ้ำ
    select * into v_sale from sales sa where sa.client_id = p_client_id;
    if found then
      return jsonb_build_object('id', v_sale.id, 'bill_no', v_sale.bill_no, 'total', v_sale.total);
    end if;
  end if;

  select s.id into v_staff from staff s where s.id = auth.uid();
  v_paid := least(coalesce(p_paid_at, now()), now());

  insert into sales (device_id, staff_id, status, client_id, created_at, customer_id)
  values (p_device, v_staff, p_status, p_client_id, v_paid, p_customer) returning * into v_sale;

  for it in select * from jsonb_array_elements(p_items) loop
    v_qty := (it->>'qty')::numeric;
    if v_qty is null or v_qty <= 0 then raise exception 'จำนวนไม่ถูกต้อง'; end if;

    select * into u from product_units pu where pu.id = (it->>'unit_id')::bigint and pu.is_active;
    if not found then raise exception 'ไม่พบหน่วยขาย %', it->>'unit_id'; end if;
    select * into p from products pr where pr.id = u.product_id;

    select coalesce(
      (select t.price from price_tiers t where t.unit_id = u.id and t.min_qty <= v_qty
        order by t.min_qty desc limit 1), u.price) into v_price;
    v_base := round(v_qty * u.base_qty, 3);

    insert into sale_items (sale_id, product_id, unit_id, product_name, unit_name, qty, base_qty, unit_price, unit_cost)
    values (v_sale.id, p.id, u.id, p.name || coalesce(' ' || p.spec, ''), u.unit_name, v_qty, v_base, v_price, u.cost)
    returning sale_items.id into v_item;

    v_sub := v_sub + round(v_qty * v_price, 2);

    if p_status = 'paid' then
      insert into stock_movements (product_id, qty_base, reason, sale_item_id, device_id, staff_id, created_at)
      values (p.id, -v_base, 'sale', v_item, p_device, v_staff, v_paid);
    end if;
  end loop;

  v_disc := least(greatest(coalesce(p_discount, 0), 0), v_sub);
  update sales s set subtotal = v_sub, discount = v_disc, total = v_sub - v_disc,
         pay_method = case when p_status = 'paid' then p_method end,
         paid_at    = case when p_status = 'paid' then v_paid end
   where s.id = v_sale.id returning * into v_sale;

  return jsonb_build_object('id', v_sale.id, 'bill_no', v_sale.bill_no, 'total', v_sale.total);
end $$;


revoke execute on function create_sale(text, bigint, text, numeric, jsonb, uuid, timestamptz, bigint) from public, anon;
grant  execute on function create_sale(text, bigint, text, numeric, jsonb, uuid, timestamptz, bigint) to authenticated;

-- ---------- 3) ใบสั่งซื้อ (เฉพาะเจ้าของร้าน) ----------
create sequence if not exists po_no_seq;
create table if not exists purchase_orders (
  id            bigint generated by default as identity primary key,
  po_no         text not null unique default ('PO' || lpad(nextval('po_no_seq')::text, 5, '0')),
  supplier_name text not null,
  status        text not null default 'ordered' check (status in ('ordered','received','cancelled')),
  note          text,
  expected_date date,
  staff_id      uuid default auth.uid(),
  created_at    timestamptz not null default now(),
  received_at   timestamptz
);
create table if not exists purchase_order_items (
  id           bigint generated by default as identity primary key,
  po_id        bigint not null references purchase_orders(id) on delete cascade,
  unit_id      bigint references product_units(id) on delete set null,
  product_id   bigint references products(id) on delete set null,
  product_name text not null,
  unit_name    text not null,
  qty          numeric(14,3) not null check (qty > 0),
  cost         numeric(12,2) not null default 0 check (cost >= 0)
);
create index if not exists po_items_po_idx on purchase_order_items (po_id);
alter table purchase_orders      enable row level security;
alter table purchase_order_items enable row level security;
drop policy if exists "owner_all" on purchase_orders;
drop policy if exists "owner_all" on purchase_order_items;
create policy "owner_all" on purchase_orders      for all to authenticated using (is_owner()) with check (is_owner());
create policy "owner_all" on purchase_order_items for all to authenticated using (is_owner()) with check (is_owner());

-- รับของตามใบสั่งซื้อ: เพิ่มสต็อก + อัปเดตราคาทุน + ปิดใบสั่งซื้อ ในธุรกรรมเดียว
create or replace function receive_purchase_order(p_po bigint) returns jsonb
language plpgsql security definer set search_path = public as $$
declare v_po purchase_orders; v_items jsonb;
begin
  if not is_owner() then raise exception 'เฉพาะเจ้าของร้านเท่านั้น'; end if;
  select * into v_po from purchase_orders where id = p_po for update;
  if not found then raise exception 'ไม่พบใบสั่งซื้อ'; end if;
  if v_po.status <> 'ordered' then raise exception 'ใบสั่งซื้อนี้ปิดไปแล้ว (%)', v_po.status; end if;
  select jsonb_agg(case when i.cost > 0 then jsonb_build_object('unit_id', i.unit_id, 'qty', i.qty, 'cost', i.cost)
                        else jsonb_build_object('unit_id', i.unit_id, 'qty', i.qty) end)
    into v_items from purchase_order_items i where i.po_id = p_po and i.unit_id is not null;
  if v_items is null then raise exception 'ใบสั่งซื้อนี้ไม่มีรายการที่รับเข้าได้ (สินค้าอาจถูกลบ)'; end if;
  perform receive_stock('purchase', 'รับตาม ' || v_po.po_no || ' (' || v_po.supplier_name || ')', v_items);
  update purchase_orders set status = 'received', received_at = now() where id = p_po;
  return jsonb_build_object('ok', true, 'po_no', v_po.po_no);
end $$;
revoke execute on function receive_purchase_order(bigint) from public, anon;
grant  execute on function receive_purchase_order(bigint) to authenticated;

-- ---------- 4) app_status: เพิ่มจำนวนหน่วยขาย (ใช้ตรวจว่านำเข้าสินค้าครบไหม) ----------
create or replace function app_status() returns jsonb language sql stable security definer set search_path = public as $$
  select jsonb_build_object(
    'role', (select s.role from staff s where s.id = auth.uid()),
    'name', (select s.name from staff s where s.id = auth.uid()),
    'has_owner', exists (select 1 from staff s where s.role = 'owner'),
    'products', (select count(*) from products),
    'units', (select count(*) from product_units where is_active));
$$;
