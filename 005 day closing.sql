-- 005_day_closing.sql — ปิดยอดประจำวัน (นับเงินสดในลิ้นชัก เทียบกับยอดที่ระบบคำนวณ)
-- รันใน Supabase > SQL Editor หนึ่งครั้ง (รันซ้ำได้)
create table if not exists day_closings (
  id            bigint generated by default as identity primary key,
  close_date    date not null,
  opening_cash  numeric(12,2) not null default 0,   -- เงินทอนตั้งต้นในลิ้นชัก
  cash_sales    numeric(12,2) not null default 0,   -- ยอดขายเงินสด
  cash_payments numeric(12,2) not null default 0,   -- รับชำระหนี้เป็นเงินสด
  other_sales   numeric(12,2) not null default 0,   -- โอน/พร้อมเพย์/อื่นๆ
  credit_sales  numeric(12,2) not null default 0,   -- ขายเชื่อ
  expected_cash numeric(12,2) not null,             -- เงินสดที่ควรมี
  counted_cash  numeric(12,2) not null,             -- เงินสดที่นับได้จริง
  diff          numeric(12,2) not null,             -- ส่วนต่าง (นับได้ - ควรมี)
  note          text,
  staff_id      uuid default auth.uid() references staff(id),
  created_at    timestamptz not null default now()
);
create index if not exists day_closings_date_idx on day_closings (close_date desc);
alter table day_closings enable row level security;
drop policy if exists "owner_all" on day_closings;
create policy "owner_all" on day_closings for all to authenticated using (is_owner()) with check (is_owner());
notify pgrst, 'reload schema';
